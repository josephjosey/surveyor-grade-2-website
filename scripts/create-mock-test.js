const optLetterToIndex = { a: 0, b: 1, c: 2, d: 3 };

function parseQuestions(text) {
  const blocks = text.trim().split(/\n\s*\n/);
  const questions = [];

  for (const block of blocks) {
    const lines = block.trim().split('\n').map(l => l.trim()).filter(Boolean);
    if (lines.length < 5) continue;

    const qLineMatch = lines[0].match(/^(\d+)\.\s*(.+)$/);
    if (!qLineMatch) continue;

    const qNum = parseInt(qLineMatch[1], 10);
    const qText = qLineMatch[2];

    const options = [];
    for (let i = 1; i <= 4; i++) {
      if (lines[i]) {
        const cleanOpt = lines[i].replace(/^[a-d]\)\s*/i, '');
        options.push(cleanOpt);
      }
    }

    const correctLetter = (keyMap[qNum] || 'a').toLowerCase();
    const correctIndex = optLetterToIndex[correctLetter] ?? 0;

    let topic = 'Basic Principles of Surveying';
    if (qText.toLowerCase().includes('hydrographic') || qText.toLowerCase().includes('marine') || qText.toLowerCase().includes('water') || qText.toLowerCase().includes('submarine')) {
      topic = 'Hydrographic Surveying';
    } else if (qText.toLowerCase().includes('cadastral') || qText.toLowerCase().includes('property') || qText.toLowerCase().includes('village')) {
      topic = 'Cadastral Surveying';
    } else if (qText.toLowerCase().includes('geodetic') || qText.toLowerCase().includes('curvature') || qText.toLowerCase().includes('earth') || qText.toLowerCase().includes('polar')) {
      topic = 'Geodetic & Earth Curvature';
    } else if (qText.toLowerCase().includes('plan') || qText.toLowerCase().includes('map') || qText.toLowerCase().includes('scale') || qText.toLowerCase().includes('rf')) {
      topic = 'Scales, Plans & Maps';
    } else if (qText.toLowerCase().includes('passometer') || qText.toLowerCase().includes('odometer') || qText.toLowerCase().includes('vernier') || qText.toLowerCase().includes('pace')) {
      topic = 'Survey Instruments & Measurements';
    } else if (qText.toLowerCase().includes('reconnaissance') || qText.toLowerCase().includes('inspection')) {
      topic = 'Reconnaissance & Field Operations';
    }

    questions.push({
      id: `q-survey-master-${qNum}`,
      questionNumber: qNum,
      question: qText,
      options,
      correctOptionIndex: correctIndex,
      explanation: `Official Kerala PSC Answer Key: Option ${correctLetter.toUpperCase()} (${options[correctIndex] || ''}). Standard reference as per Kerala PSC Survey & Land Records curriculum.`,
      rankerTip: `Remember: Key concept frequently tested in Kerala PSC Surveyor Grade II & Overseer exams.`,
      topic
    });
  }

  return questions;
}

